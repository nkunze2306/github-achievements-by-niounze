// Honest line counts: removes lines that are not hand-written code of yours.
//
// A commit that adds a whole Unity project, a lock file, a vendored library or generated code can carry tens of thousands of
// lines that nobody typed. GitHub only reports one number per commit, so for LARGE commits this module asks for the file list
// and drops every file that matches the rules in this file (or your own `exclude-lines` patterns). Small commits are taken as
// they are (they are cheap to trust and would cost one API call each).
//
//   LINES_FILTER=0              switch the filter off (raw GitHub numbers)
//   LINES_THRESHOLD=500         commits with fewer changed lines than this are not inspected
//   LINES_MAX_CALLS=800         API calls per run for file lists (results are cached, so the next runs are cheap)
//   LINES_UNVERIFIED_CAP=20000  a huge commit whose files cannot be read counts as a bulk import and is not counted
//   STATS_EXCLUDE=a,b           extra patterns, for example "Assets/MyGenerated/**,*.dump.txt" (* = one folder level, ** = any depth)
//   LINES_CACHE=path.json       cache file (set by run.mjs); commit contents never change, so cached answers stay valid
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const ON = process.env.LINES_FILTER !== '0';
const THRESHOLD = Number(process.env.LINES_THRESHOLD || 500);
const MAX_CALLS = Number(process.env.LINES_MAX_CALLS || 800);
const UNVERIFIED_CAP = Number(process.env.LINES_UNVERIFIED_CAP || 20000);
const TOKEN = (process.env.STATS_TOKEN || process.env.GITHUB_TOKEN || '').trim();
const CACHE_FILE = process.env.LINES_CACHE || '';

// folders that never contain code you wrote (matched on any path segment, case-insensitive)
const DIRS = new Set([
  // dependencies and build output
  'node_modules', 'bower_components', 'vendor', 'third_party', 'third-party', 'thirdparty', 'extern', 'external', 'pods', 'carthage',
  'dist', 'out', 'target', 'bin', 'obj', '.next', '.nuxt', '.svelte-kit', '.cache', '.parcel-cache', '.turbo', 'coverage', '__pycache__',
  '.venv', 'venv', 'site-packages', '.tox', '.gradle', '.dart_tool', '.pub-cache', 'deriveddata', 'xcuserdata',
  // editors, Godot
  '.idea', '.vs', '.vscode', '.godot', '.import',
]);
// folder names that are only meant when the commit really is a Unity or Unreal project (a plain "library" or "logs" folder can be real code)
const UNITY_DIRS = new Set(['library', 'temp', 'logs', 'usersettings', 'memorycaptures', 'builds', 'build', 'projectsettings', 'plugins', 'textmesh pro', 'streamingassets', 'assetstoretools', 'samples~', 'gizmos', 'packages']);
const UNREAL_DIRS = new Set(['intermediate', 'binaries', 'saved', 'deriveddatacache', 'content']);

// exact file names
const NAMES = new Set([
  'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lockb', 'cargo.lock', 'poetry.lock', 'pipfile.lock',
  'composer.lock', 'gemfile.lock', 'go.sum', 'packages.lock.json', 'gradle.lockfile', 'flake.lock', 'pubspec.lock', 'podfile.lock',
  'packages-lock.json', 'manifest.json.lock', '.ds_store', 'thumbs.db',
  'license', 'licence', 'copying', 'notice', 'license.md', 'license.txt', 'licence.md', 'licence.txt',
  '.gitignore', '.gitattributes', '.gitmodules', '.editorconfig', '.dockerignore',
]);

// extensions of files an editor, a tool or an asset pipeline writes (not you)
const EXT = new Set([
  // Unity / Unreal / Godot assets
  'meta', 'unity', 'prefab', 'asset', 'mat', 'anim', 'controller', 'overridecontroller', 'physicmaterial', 'physicsmaterial2d', 'mask',
  'flare', 'cubemap', 'lighting', 'terrainlayer', 'playable', 'signal', 'mixer', 'spriteatlas', 'shadergraph', 'shadersubgraph', 'vfx',
  'uasset', 'umap', 'tscn', 'tres', 'import', 'unitypackage',
  // IDE project files
  'sln', 'csproj', 'vcxproj', 'pbxproj', 'xcworkspacedata', 'xcscheme', 'storyboard', 'xib', 'nib', 'iml', 'suo', 'user',
  // minified, maps, bundles, snapshots, logs
  'map', 'snap', 'log', 'tmp', 'bak', 'lock', 'lockb',
  // data, notebooks, vector and 3D exports
  'csv', 'tsv', 'parquet', 'ipynb', 'svg', 'obj', 'fbx', 'dae', 'gltf', 'mtl', 'stl', 'ply', 'dump',
]);

// generated source (suffix match on the lower-case file name)
const SUFFIXES = [
  '.min.js', '.min.css', '.bundle.js', '.chunk.js', '.designer.cs', '.g.cs', '.g.i.cs', '.generated.cs', '.pb.go', '.pb.cc', '.pb.h',
  '_pb2.py', '_pb2_grpc.py', '.pb.js', '.freezed.dart', '.g.dart', '.gen.go', '.generated.ts', '.generated.js', '.d.ts.map',
  '.xcodeproj/project.pbxproj',
];
const GENERATED = /(^|[._-])(generated|autogenerated|auto-generated)([._-]|$)/;

function globToRegex(g) {
  const p = g.trim().replace(/^\.?\//, '').toLowerCase();
  const esc = p.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*\*/g, '\u0000').replace(/\*/g, '[^/]*').replace(/\u0000/g, '.*').replace(/\?/g, '[^/]');
  // a pattern without a slash matches that name anywhere, one with a slash matches from the repo root or any folder
  return new RegExp(p.includes('/') ? `(^|/)${esc}($|/)` : `(^|/)${esc}($|/)`);
}
const EXTRA = (process.env.STATS_EXCLUDE || '').split(',').map((s) => s.trim()).filter(Boolean).map(globToRegex);

// ctx.unity / ctx.unreal: the commit contains files that show it is a Unity / Unreal project
export function isNoise(path, ctx = {}) {
  const p = String(path || '').replace(/\\/g, '/').toLowerCase();
  const parts = p.split('/'), file = parts[parts.length - 1], dirs = parts.slice(0, -1);
  if (dirs.some((d) => DIRS.has(d))) return true;
  if (ctx.unity && dirs.some((d) => UNITY_DIRS.has(d))) return true;
  if (ctx.unreal && dirs.some((d) => UNREAL_DIRS.has(d))) return true;
  if (NAMES.has(file)) return true;
  const dot = file.lastIndexOf('.');
  if (dot > 0 && EXT.has(file.slice(dot + 1))) return true;
  if (SUFFIXES.some((s) => p.endsWith(s))) return true;
  if (GENERATED.test(file)) return true;
  return EXTRA.some((re) => re.test(p));
}

// is this commit part of a Unity / Unreal project? (decided from the file list of the commit)
function projectKind(paths) {
  const l = paths.map((x) => String(x || '').toLowerCase());
  return {
    unity: l.some((x) => x.endsWith('.meta') || x.includes('projectsettings/projectversion.txt') || /(^|\/)assets\/.*\.(unity|prefab)$/.test(x)),
    unreal: l.some((x) => x.endsWith('.uproject') || x.endsWith('.uasset') || x.endsWith('.umap')),
  };
}

// ---- cache: oid -> [additions, deletions]; reset when the rules change
const RULES = JSON.stringify([ON, THRESHOLD, [...DIRS], [...UNITY_DIRS], [...UNREAL_DIRS], [...NAMES], [...EXT], SUFFIXES, process.env.STATS_EXCLUDE || '']);
let cache = { rules: RULES, commits: {} }, dirty = false;
if (CACHE_FILE && existsSync(CACHE_FILE)) {
  try { const j = JSON.parse(readFileSync(CACHE_FILE, 'utf8')); if (j.rules === RULES && j.commits) cache = j; } catch { /* start fresh */ }
}
const stat = { inspected: 0, cached: 0, calls: 0, removed: 0, unverified: 0, bulk: 0, commits: 0 };

async function githubFiles(repo, oid) {
  const files = [];
  for (let page = 1; page <= 30; page++) {
    stat.calls++;
    const res = await fetch(`https://api.github.com/repos/${repo}/commits/${oid}?per_page=100&page=${page}`, { headers: { Authorization: `bearer ${TOKEN}`, Accept: 'application/vnd.github+json' } });
    if (res.status !== 200) return files.length ? files : null;
    const j = await res.json();
    files.push(...(j.files || []));
    if ((j.files || []).length < 100) break;
  }
  return files;
}

// returns the commit with additions/deletions reduced to the lines of files that count
export async function adjustCommit(c, repo) {
  if (!TOKEN) return c;
  return adjustWith(c, async () => (await githubFiles(repo, c.oid))?.map((f) => ({ path: f.filename, additions: f.additions || 0, deletions: f.deletions || 0 })) || null);
}

// same for any source: getFiles() resolves to [{ path, additions, deletions }] or null when the list cannot be read
export async function adjustWith(c, getFiles) {
  if (!ON || (c.parents?.totalCount ?? 1) > 1) return c;
  // the same commit shows up once per branch it is on: the second time costs nothing and is not counted again in the report
  const again = seenOids.get(c.oid);
  if (again) return { ...c, additions: again[0], deletions: again[1] };
  const r = await adjustOnce(c, getFiles);
  seenOids.set(c.oid, [r.additions, r.deletions]);
  return r;
}
const seenOids = new Map();

async function adjustOnce(c, getFiles) {
  stat.commits++;
  const size = (c.additions || 0) + (c.deletions || 0);
  if (size < THRESHOLD) return c;
  const hit = cache.commits[c.oid];
  if (hit) { stat.cached++; stat.removed += size - hit[0] - hit[1]; return { ...c, additions: hit[0], deletions: hit[1] }; }
  if (stat.calls >= MAX_CALLS) { stat.unverified++; return capUnverified(c, size); }
  stat.inspected++;
  let files = null;
  try { files = await getFiles(); } catch { /* handled below */ }
  if (!files) { stat.unverified++; return capUnverified(c, size); }
  const { additions, deletions } = sumCounted(files);
  cache.commits[c.oid] = [additions, deletions]; dirty = true;
  stat.removed += size - additions - deletions;
  return { ...c, additions, deletions };
}
export const countCall = () => { stat.calls++; };

// a very large commit that could not be read is far more likely an import than typing: not counted (not cached, so a later run can still verify it)
function capUnverified(c, size) {
  if (size > UNVERIFIED_CAP) { stat.bulk++; stat.removed += size; return { ...c, additions: 0, deletions: 0 }; }
  return c;
}

// for sources that bring their own file list (GitLab): same rules, given [{ path, additions, deletions }]
export function sumCounted(files) {
  const ctx = projectKind(files.map((f) => f.path));
  let a = 0, d = 0;
  for (const f of files) if (!isNoise(f.path, ctx)) { a += f.additions; d += f.deletions; }
  return { additions: a, deletions: d };
}
export const lineFilter = { on: ON, threshold: THRESHOLD, maxCalls: MAX_CALLS };
export function noteRemoved(n) { stat.removed += n; }

export function flushLines(label = '') {
  if (CACHE_FILE && dirty) { try { writeFileSync(CACHE_FILE, JSON.stringify(cache)); } catch { /* cache is optional */ } }
  if (!ON) { console.log(`${label}line filter: off`); return; }
  console.log(`${label}line filter: ${stat.removed} lines of generated, vendored or project-setup files are not counted ` +
    `(${stat.inspected} large commits inspected, ${stat.cached} from cache${stat.unverified ? `, ${stat.unverified} could not be read` : ''}${stat.bulk ? `, ${stat.bulk} unreadable bulk imports skipped` : ''})`);
  return { ...stat };
}
