// Rewrites the themes section of README.md (between the THEMES markers) from the real theme registry.
//   node tools/make-readme-themes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { THEMES } from '../stats/themes/index.mjs';
import { rangeOf } from '../stats/theme.mjs';

const README = fileURLToPath(new URL('../README.md', import.meta.url));

const kind = (c) => (c.type === 'range' ? 'number' : c.type === 'toggle' ? 'true / false' : 'colour (#rrggbb)');
const range = (c) => {
  if (c.type === 'range') { const [lo, hi] = rangeOf(c); return `${lo} to ${hi}${c.step ? `, step ${c.step / (c.scale || 1)}` : ''}${c.unit ? ` (${c.unit})` : ''}`; }
  if (c.type === 'toggle') return 'on or off';
  return `any hex colour, presets: ${c.colors.map((x) => `\`${x}\``).join(' ')}`;
};
const code = (v) => `\`${v}\``;
const table = (rows) => ['| Setting | What it does | Values | Default |', '| --- | --- | --- | --- |', ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');

const block = `<!-- THEMES:START (generated by tools/make-readme-themes.mjs) -->
Animated, pure SVG overlays (no script, no web fonts), so they also run inside a README image. Pick them in ${code('theme.json')} (next to your generated files) or with the "Theme & look" bar of the dashboard. Several overlays can be combined. Details and examples: [${code('docs/THEMES.md')}](docs/THEMES.md).

| Overlay | Look | Own settings (under ${code('options.<id>')}) |
| --- | --- | --- |
| ${code('autumn')} (default) | falling leaves, leaf piles on the cards | general: ${code('density')}, ${code('piles')}, ${code('wind')} |
| ${code('butterflies')} | pixel butterflies that land on card edges | general: ${code('density')} |
${THEMES.map((t) => `| ${code(t.id)} | ${t.description} | ${t.controls.map((c) => code(c.key)).join(', ')} |`).join('\n')}

**General settings** (top level of ${code('theme.json')})

${table([
  [code('overlays'), 'Which overlays are drawn', 'list of overlay ids', code('["autumn"]')],
  [code('ring'), 'Progress ring style of the achievement tiles', '`classic`, `orbit`, `rank`, `rarity`', code('classic')],
  [code('density'), 'Amount in Autumn and Butterflies', 'integer 1 to 5', code('3')],
  [code('piles'), 'Autumn: leaves lying on card edges', 'true / false', code('true')],
  [code('wind'), 'Autumn: gusts', 'true / false', code('true')],
  [code('reduceMotion'), 'Stop all movement for visitors who prefer reduced motion', 'true / false', code('true')],
])}

${THEMES.map((t) => `<details>
<summary><b>${t.label}</b> (<code>options.${t.id}</code>)</summary>

${t.description}

${table(t.controls.map((c) => [code(c.key), c.label, `${kind(c)}: ${range(c)}`, code(t.defaults[c.key])]))}

</details>`).join('\n\n')}
<!-- THEMES:END -->`;

const cur = readFileSync(README, 'utf8');
const crlf = cur.includes('\r\n');
const norm = cur.replace(/\r\n/g, '\n');
const out = norm.replace(/<!-- THEMES:START[\s\S]*?<!-- THEMES:END -->/, () => block);
writeFileSync(README, crlf ? out.replace(/\n/g, '\r\n') : out);
console.log('updated the themes section of README.md');
