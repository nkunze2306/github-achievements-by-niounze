// Rewrites the themes section of README.md (between the THEMES markers) from the real theme registry.
//   node tools/make-readme-themes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { THEMES } from '../stats/themes/index.mjs';
import { rangeOf } from '../stats/theme.mjs';

const README = fileURLToPath(new URL('../README.md', import.meta.url));

const kind = (c) => (c.type === 'range' ? 'number' : c.type === 'toggle' ? 'true / false' : 'colour (#rrggbb)');
const range = (c) => {
  if (c.type === 'range') { const [lo, hi] = rangeOf(c); return `${lo} to ${hi}${c.step ? `, step ${c.step / (c.scale || 1)}` : ''}${c.unit ? ` (${c.unit})` : ''}`; }
  if (c.type === 'toggle') return 'on or off';
  return `any hex colour, presets: ${c.colors.map((x) => `\`${x}\``).join(' ')}`;
};
const code = (v) => `\`${v}\``;
const table = (rows) => ['| Setting | What it does | Values | Default |', '| --- | --- | --- | --- |', ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');

// every overlay gets a small excerpt (top of the card, cropped via viewBox) so the section stays short
const ALL = [
  { id: 'autumn', label: 'Autumn (default)', description: 'Falling leaves, piles on the card edges.', controls: [] },
  { id: 'butterflies', label: 'Butterflies', description: 'Pixel butterflies landing on the cards.', controls: [] },
  ...THEMES,
];
const CROP_H = 330;
for (const t of ALL) {
  const src = fileURLToPath(new URL(`../docs/img/stats-${t.id}.svg`, import.meta.url));
  const dst = fileURLToPath(new URL(`../docs/img/theme-${t.id}.svg`, import.meta.url));
  const svg = readFileSync(src, 'utf8');
  writeFileSync(dst, svg.replace(/^<svg([^>]*?)width="(\d+)" height="\d+" viewBox="0 0 (\d+) \d+"/, (m, pre, w) => `<svg${pre}width="${w}" height="${CROP_H}" viewBox="0 0 ${w} ${CROP_H}"`));
}
const cell = (t) => `<img src="docs/img/theme-${t.id}.svg" alt="${t.label} theme" width="100%"><br><b>${t.label}</b><br>${t.description}`;
const gallery = `<table>
${[0, 2, 4].map((i) => `<tr>${ALL.slice(i, i + 2).map((t) => `<td width="50%" valign="top">${cell(t)}</td>`).join('')}</tr>`).join('\n')}
</table>`;
const rows = THEMES.flatMap((t) => t.controls.map((c, i) => [i ? '' : `**${t.label}**`, code(c.key), c.label, `${kind(c)}: ${range(c)}`, code(t.defaults[c.key])]));
const optionTable = ['| Overlay | Setting (`options.<id>`) | What it does | Values | Default |', '| --- | --- | --- | --- | --- |', ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');

const block = `<!-- THEMES:START (generated by tools/make-readme-themes.mjs) -->
Animated, pure SVG overlays (no script, no web fonts), so they also run inside a README image. Pick them in ${code('theme.json')} or with the dashboard settings below. Several overlays can be combined. More detail and examples: [${code('docs/THEMES.md')}](docs/THEMES.md).

${gallery}

<details>
<summary><b>All settings</b> (general and per overlay)</summary>

${table([
  [code('overlays'), 'Which overlays are drawn', 'list of overlay ids', code('["autumn"]')],
  [code('ring'), 'Progress ring style of the achievement tiles', '`classic`, `orbit`, `rank`, `rarity`', code('classic')],
  [code('density'), 'Amount in Autumn and Butterflies', 'integer 1 to 5', code('3')],
  [code('piles'), 'Autumn: leaves lying on card edges', 'true / false', code('true')],
  [code('wind'), 'Autumn: gusts', 'true / false', code('true')],
  [code('reduceMotion'), 'Stop all movement for visitors who prefer reduced motion', 'true / false', code('true')],
])}

${optionTable}

</details>
<!-- THEMES:END -->`;

const cur = readFileSync(README, 'utf8');
const crlf = cur.includes('\r\n');
const norm = cur.replace(/\r\n/g, '\n');
const out = norm.replace(/<!-- THEMES:START[\s\S]*?<!-- THEMES:END -->/, () => block);
writeFileSync(README, crlf ? out.replace(/\n/g, '\r\n') : out);
console.log('updated the themes section of README.md');
